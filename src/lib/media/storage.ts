import "server-only";
import { mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { s3ConfigFromEnv, s3Storage } from "./s3";

/**
 * Where uploaded files are stored. The app only talks to this interface.
 *
 * - MEDIA_STORAGE=local (default): files in MEDIA_DIR (default ./data/uploads) – dev and single server
 * - MEDIA_STORAGE=s3: S3-compatible object storage (e.g. Hetzner Object Storage, EU region), see s3.ts
 *
 * Each environment needs its own folder, bucket or S3_PREFIX: the media cleanup deletes every stored file
 * that has no row in *its* database.
 */
export interface MediaStorage {
  put(key: string, data: Uint8Array, contentType?: string): Promise<void>;
  get(key: string): Promise<Uint8Array | null>;
  delete(key: string): Promise<void>;
  /** All stored files (used by the cleanup to find files without a database row). */
  list(): AsyncIterable<StoredObject>;
}

export interface StoredObject {
  key: string;
  lastModified: Date;
}

export const SAFE_KEY = /^[A-Za-z0-9_-]+\.[a-z0-9]+$/; // keys are generated by us; never allow path tricks

function checkedKey(key: string) {
  if (!SAFE_KEY.test(key)) throw new Error(`Invalid media key: ${key}`);
  return key;
}

function localDiskStorage(dir: string): MediaStorage {
  const resolve = (key: string) => path.join(dir, checkedKey(key));
  return {
    async put(key, data) {
      await mkdir(dir, { recursive: true });
      await writeFile(resolve(key), data);
    },
    async get(key) {
      try {
        return await readFile(resolve(key));
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw e;
      }
    },
    async delete(key) {
      await rm(resolve(key), { force: true });
    },
    async *list() {
      let names: string[];
      try {
        names = await readdir(dir);
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code === "ENOENT") return;
        throw e;
      }
      for (const key of names) {
        if (!SAFE_KEY.test(key)) continue;
        const info = await stat(path.join(dir, key)).catch(() => null);
        if (info?.isFile()) yield { key, lastModified: info.mtime };
      }
    },
  };
}

/** Wraps a storage so that every key is validated, whatever the backend. */
function withKeyCheck(storage: MediaStorage): MediaStorage {
  return {
    put: async (key, data, contentType) => storage.put(checkedKey(key), data, contentType),
    get: async (key) => storage.get(checkedKey(key)),
    delete: async (key) => storage.delete(checkedKey(key)),
    list: () => storage.list(),
  };
}

export function getMediaStorage(): MediaStorage {
  const kind = process.env.MEDIA_STORAGE ?? "local";
  if (kind === "local") return localDiskStorage(path.resolve(process.env.MEDIA_DIR ?? "./data/uploads"));
  if (kind === "s3") return withKeyCheck(s3Storage(s3ConfigFromEnv()));
  throw new Error(`Unknown MEDIA_STORAGE "${kind}" (use "local" or "s3")`);
}
